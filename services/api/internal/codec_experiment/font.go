var (
	glyphUnknown = glyph{"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"}
	glyphCols    = map[rune][glyphW]uint8{}
)

func init() {
	for r, g := range glyphs {
		glyphCols[r] = colsOf(g)
	}
	glyphCols['?'] = colsOf(glyphUnknown)
}

func colsOf(g glyph) [glyphW]uint8 {
	var cols [glyphW]uint8
	for y := 0; y < glyphH; y++ {
		row := g[y]
		for x := 0; x < glyphW && x < len(row); x++ {
			if row[x] == '#' {
				cols[x] |= 1 << uint(y)
			}
		}
	}
	return cols
}

// glyphWidth is the pixel width of s rendered at the given scale.
func textWidth(s string, scale int) int {
	if len(s) == 0 {
		return 0
	}
	return len(s)*glyphAdv*scale - scale
}
